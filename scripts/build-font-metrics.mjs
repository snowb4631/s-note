// Generates the advance-width table shared by the browser preview and the PDF,
// and the woff2 the browser loads. Run: npm run fonts:metrics
import fs from "node:fs";
import * as fontkit from "fontkit";
import ttf2woff2 from "ttf2woff2";

const ttf = "src/fonts/NanumPenScript-Regular.ttf";
const font = fontkit.openSync(ttf);
const chars = [...font.characterSet].sort((a, b) => a - b);

const ranges = [];
let widths = "";
for (const cp of chars) {
  const last = ranges.at(-1);
  if (last && last[0] + last[1] === cp) last[1] += 1;
  else ranges.push([cp, 1]);
  const advance = font.glyphForCodePoint(cp).advanceWidth;
  if (advance >= 36 * 36) throw new Error(`advance too wide: ${advance}`);
  widths += advance.toString(36).padStart(2, "0");
}

fs.writeFileSync(
  "src/lib/card/metrics.generated.ts",
  `// Generated by scripts/build-font-metrics.mjs. Do not edit.\n` +
    `export const UNITS_PER_EM = ${font.unitsPerEm};\n` +
    `export const RANGES: readonly (readonly [number, number])[] = ${JSON.stringify(ranges)};\n` +
    `export const WIDTHS = "${widths}";\n`,
);
fs.writeFileSync("src/fonts/NanumPenScript-Regular.woff2", ttf2woff2(fs.readFileSync(ttf)));
console.log(`chars=${chars.length} ranges=${ranges.length}`);
